"""Builds the downloadable report. This is `pdf_service.py` from the outline."""

from __future__ import annotations

import io
from datetime import datetime, timezone

from reportlab.lib import colors
from reportlab.lib.enums import TA_JUSTIFY
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.services.calculator import calculate, format_value

BRAND = colors.HexColor("#1baf7a")
INK = colors.HexColor("#0b0b0b")
MUTED = colors.HexColor("#6b6a66")
HAIRLINE = colors.HexColor("#d9d8d2")


def _styles() -> dict:
    base = getSampleStyleSheet()
    return {
        "title": ParagraphStyle(
            "T", parent=base["Title"], fontSize=24, leading=28, textColor=INK, spaceAfter=4
        ),
        "subtitle": ParagraphStyle(
            "St", parent=base["Normal"], fontSize=11, leading=15, textColor=MUTED, spaceAfter=18
        ),
        "h2": ParagraphStyle(
            "H2", parent=base["Heading2"], fontSize=14, leading=18,
            textColor=INK, spaceBefore=16, spaceAfter=8,
        ),
        "body": ParagraphStyle(
            "B", parent=base["BodyText"], fontSize=10, leading=15,
            textColor=INK, alignment=TA_JUSTIFY, spaceAfter=8,
        ),
        "small": ParagraphStyle(
            "S", parent=base["Normal"], fontSize=8, leading=11, textColor=MUTED
        ),
    }


def _esc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_report_pdf(
    *, company: dict, year: int, framework: str, sections: list[dict], values: dict
) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=20 * mm, rightMargin=20 * mm, topMargin=18 * mm, bottomMargin=18 * mm,
        title=f"{company.get('name')} ESG Report {year}",
        author="Verdant ESG",
    )
    s = _styles()
    story: list = []

    story.append(Paragraph(_esc(company.get("name", "Company")), s["title"]))
    meta = f"ESG Report · FY {year} · {framework}"
    if company.get("industry"):
        meta += f" · {_esc(company['industry'])}"
    story.append(Paragraph(meta, s["subtitle"]))

    calc = calculate(values or {})
    if calc:
        rows = [["Metric", "Value", "Unit", "Basis"]]
        for m in calc:
            rows.append([
                m["label"], format_value(m["value"], m["unit"]),
                m["unit"], m.get("basis", "—"),
            ])
        table = Table(rows, colWidths=[52 * mm, 26 * mm, 24 * mm, 68 * mm], repeatRows=1)
        table.setStyle(TableStyle([
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 8),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("BACKGROUND", (0, 0), (-1, 0), BRAND),
            ("TEXTCOLOR", (0, 1), (-1, -1), INK),
            ("TEXTCOLOR", (3, 1), (3, -1), MUTED),
            ("ALIGN", (1, 0), (2, -1), "RIGHT"),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("GRID", (0, 0), (-1, -1), 0.4, HAIRLINE),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f6f6f3")]),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]))
        story.append(Paragraph("Calculated metrics", s["h2"]))
        story.append(table)
        story.append(Spacer(1, 6))
        story.append(Paragraph(
            "Scope 2 is location-based, using the CEA grid factor 0.727 kg CO₂e/kWh "
            "(FY 2023-24). Scope 3 is not calculated.", s["small"]
        ))
        story.append(PageBreak())

    for sec in sections:
        body = (sec.get("body") or "").strip()
        if not body:
            continue
        story.append(Paragraph(_esc(sec.get("title", "")), s["h2"]))
        for para in body.split("\n\n"):
            para = para.strip()
            if para:
                story.append(Paragraph(_esc(para).replace("\n", "<br/>"), s["body"]))
        if not sec.get("usedAi", False):
            story.append(Paragraph(
                "This section was produced by the deterministic template, not a "
                "language model.", s["small"]
            ))
        story.append(Spacer(1, 4))

    story.append(Spacer(1, 14))
    story.append(Paragraph(
        "Generated by Verdant ESG on "
        f"{datetime.now(timezone.utc).strftime('%d %B %Y')}. "
        "Readiness indicators and drafted text are decision support, not assurance. "
        "Figures should be reviewed before filing against SEBI's BRSR format or the ESRS. "
        "Scope 3 emissions are not calculated and no double-materiality assessment has "
        "been performed.",
        s["small"],
    ))

    doc.build(story)
    return buf.getvalue()
